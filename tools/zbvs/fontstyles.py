"""Render the per-variant font style table consumed by the C# extension.

Visual Studio themes can't carry bold/italic, so the extension applies them
at runtime when the editor background matches a zenbones variant.
"""

from __future__ import annotations

from .theme import role_styles
from .vimcolors import Variant
from .vsdirect import LANGUAGE_SERVICE, OVERLAYS, SYNTAX

_FLAGS = {
    "bold": "Style.Bold",
    "italic": "Style.Italic",
    "nobold": "Style.NoBold",
    "noitalic": "Style.NoItalic",
}


def classification_styles(v: Variant) -> dict[str, frozenset[str]]:
    """Classification name -> styles, omitting unstyled classifications.

    Besides "bold" and "italic", overlays get "nobold" / "noitalic" to cancel
    styles inherited from the classification they're drawn over.
    """
    styles = role_styles(v)
    table: dict[str, tuple[str, frozenset[str]]] = {}
    for name, role in [*SYNTAX.items(), *LANGUAGE_SERVICE.items()]:
        own = styles.get(role, frozenset())
        if name in OVERLAYS:
            under = styles[SYNTAX[OVERLAYS[name]]]
            own = own | {"no" + s for s in under - own}
        # Classification names are case-insensitive ("keyword" == "Keyword").
        if own and name.lower() not in table:
            table[name.lower()] = (name, frozenset(own))
    return {name: s for _, (name, s) in sorted(table.items())}


def _csharp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_csharp(variants: list[Variant]) -> str:
    lines = [
        "// <auto-generated>",
        "// Generated by tools/generate.py from zenbones.nvim. Do not edit.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace ZenbonesTheme",
        "{",
        "    internal static partial class FontStyles",
        "    {",
        "        // Editor background (0xRRGGBB) -> classification -> style.",
        "        private static readonly Dictionary<int, Dictionary<string, Style>> s_byBackground =",
        "            new Dictionary<int, Dictionary<string, Style>>",
        "            {",
    ]
    for v in variants:
        bg = v.bg("Normal")
        assert bg
        lines.append(f"                // {v.id}")
        lines.append(f"                [0x{bg[1:7]}] = new Dictionary<string, Style>(StringComparer.OrdinalIgnoreCase)")
        lines.append("                {")
        for name, styles in classification_styles(v).items():
            flags = " | ".join(_FLAGS[s] for s in sorted(styles))
            lines.append(f"                    [{_csharp_string(name)}] = {flags},")
        lines.append("                },")
    lines += ["            };", "    }", "}", ""]
    return "\r\n".join(lines)
